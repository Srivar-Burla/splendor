"""Download the latin WOFF2 files for the UI typefaces and write fonts.css."""

import os
import re
import urllib.request

CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Fraunces:opsz,wght@9..144,400;9..144,500;9..144,600;9..144,700"
    "&family=Public+Sans:wght@400;500;600;700&display=swap"
)
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/124.0 Safari/537.36"
)
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.normpath(os.path.join(HERE, "..", "static", "fonts"))
CSS_OUT = os.path.normpath(os.path.join(HERE, "..", "static", "fonts.css"))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    req = urllib.request.Request(CSS_URL, headers={"User-Agent": UA})
    css = urllib.request.urlopen(req, timeout=30).read().decode("utf-8")

    pattern = re.compile(r"/\*\s*latin\s*\*/\s*@font-face\s*\{(.*?)\}", re.S)
    faces = []
    for block in pattern.findall(css):
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
        url = re.search(r"src:\s*url\(([^)]+)\)", block).group(1)
        slug = family.lower().replace(" ", "-")
        filename = f"{slug}-{weight}-{style}.woff2"
        path = os.path.join(OUT_DIR, filename)
        if not os.path.exists(path):
            data = urllib.request.urlopen(url, timeout=30).read()
            with open(path, "wb") as fh:
                fh.write(data)
        faces.append((family, style, weight, filename))
        print(f"  {family} {weight} {style} -> {filename} ({os.path.getsize(path)} bytes)")

    lines = ["/* Bundled from Google Fonts (OFL). Generated by tools/fetch_fonts.py. */\n"]
    for family, style, weight, filename in faces:
        lines.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/static/fonts/{filename}') format('woff2');\n"
            "}\n"
        )
    with open(CSS_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"\nWrote {CSS_OUT}")


if __name__ == "__main__":
    main()
